import { CHIPS } from "./chips";
import type { Design } from "./design";
import { planPins } from "./matrix";

export interface Keymap {
  design: string;
  chip: string;
  rows: string[];
  columns: string[];
  /** [row][column] -> action, or null for an empty matrix position. */
  map: (string | null)[][];
  irTransmit: string | null;
  irReceive: string | null;
  battery: string | null;
}

export function keymap(design: Design): Keymap {
  const plan = planPins(design);
  if (!plan.ok) throw new Error(plan.reason);
  const map: (string | null)[][] = plan.rows.map(() => plan.columns.map(() => null));
  for (const key of design.keys) {
    const at = plan.positions.get(key.id);
    if (at) map[at[0]]![at[1]] = key.action;
  }
  return {
    design: design.name,
    chip: CHIPS[design.chip].label,
    rows: plan.rows.map((p) => p.chipPin),
    columns: plan.columns.map((p) => p.chipPin),
    map,
    irTransmit: plan.irTransmit?.chipPin ?? null,
    irReceive: plan.irReceive?.chipPin ?? null,
    battery: plan.battery?.chipPin ?? null,
  };
}

/* C header for the ESP-IDF firmware. Pins are GPIO numbers; -1 marks an unused option. */
export function keymapHeader(design: Design): string {
  const chip = CHIPS[design.chip];
  if (chip.firmware !== "esp-idf") throw new Error(`${chip.label} has no ESP-IDF firmware; export the JSON keymap instead.`);
  const plan = planPins(design);
  if (!plan.ok) throw new Error(plan.reason);
  const km = keymap(design);
  const gpio = (chipPin: string | null) => chipPin ? String(chip.pins.find((p) => p.chipPin === chipPin)?.gpio ?? -1) : "-1";
  const rows = km.map.map((row) => `    {${row.map((a) => (a ? `"${a}"` : "NULL")).join(", ")}}`).join(",\n");
  return `/* Generated by Open Remote Designer from "${design.name}" for ${chip.label}. Do not edit. */
#pragma once
#include <stddef.h>

#define OR_MATRIX_ROWS ${plan.rows.length}
#define OR_MATRIX_COLS ${plan.columns.length}
#define OR_IR_TX_GPIO ${gpio(km.irTransmit)}
#define OR_IR_RX_GPIO ${gpio(km.irReceive)}
#define OR_BATTERY_GPIO ${gpio(km.battery)}

static const int or_row_gpio[OR_MATRIX_ROWS] = {${plan.rows.map((p) => p.gpio).join(", ")}};
static const int or_col_gpio[OR_MATRIX_COLS] = {${plan.columns.map((p) => p.gpio).join(", ")}};
static const char *const or_keymap[OR_MATRIX_ROWS][OR_MATRIX_COLS] = {
${rows}
};
`;
}
